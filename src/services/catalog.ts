export function formatBytes(bytes: number): string {
  if (bytes === 0) return '0 B';
  const k = 1024;
  const sizes = ['B', 'KB', 'MB', 'GB', 'TB'];
  const i = Math.floor(Math.log(bytes) / Math.log(k));
  return `${parseFloat((bytes / Math.pow(k, i)).toFixed(1))} ${sizes[i]}`;
}

export function normalizePackageStorage(pkg: Package): Package {
  const downloadBytes = pkg.downloadSizeBytes || pkg.sizeBytes || 45000000;
  // Installed footprint on disk typically extracts to ~3x - 4x of installer package
  const installedBytes = pkg.installedSizeBytes || Math.round(downloadBytes * 3.4);

  return {
    ...pkg,
    sizeBytes: downloadBytes,
    formattedSize: pkg.formattedSize || formatBytes(downloadBytes),
    downloadSizeBytes: downloadBytes,
    formattedDownloadSize: pkg.formattedDownloadSize || formatBytes(downloadBytes),
    installedSizeBytes: installedBytes,
    formattedInstalledSize: pkg.formattedInstalledSize || formatBytes(installedBytes),
    requiredStorageDisk: pkg.requiredStorageDisk || 'C:\\ (NTFS)',
  };
}

